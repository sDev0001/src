# ============================================================================
#  AGENT RAG LOCAL -- INSTALARE DINTR-UN SINGUR FISIER
#
#  Copiaza acest fisier pe server si ruleaza:
#
#      sudo bash agent-bundle.sh
#
#  Nu trebuie sa dezarhivezi nimic, sa intri in vreun folder sau sa editezi
#  ceva. Instaleaza dependentele, compileaza llama.cpp daca lipseste, descarca
#  modelul de embeddings, porneste serverele, indexeaza documentele si te lasa
#  in prompt.  Ruleaza-l de cate ori vrei: sare peste ce e deja facut.
