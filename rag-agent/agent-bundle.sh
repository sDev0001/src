writable() { mkdir -p "$1" 2>/dev/null && [ -d "$1" ] && [ -w "$1" ]; }
if ! writable "$DEST"; then
  if command -v sudo >/dev/null 2>&1; then
    sudo mkdir -p "$DEST" 2>/dev/null
    sudo chown "$(id -u):$(id -g)" "$DEST" 2>/dev/null
  fi
  if ! writable "$DEST"; then
    DEST="$HOME/rag-agent"
    writable "$DEST" || { echo "Nu pot scrie nici in $DEST. Ruleaza ca root." >&2; exit 1; }
    echo "    (folosesc $DEST)"
  fi
fi

echo "==> Despachetez in $DEST"
