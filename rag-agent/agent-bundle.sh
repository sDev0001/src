# ============================================================================
#  AGENT RAG LOCAL -- INSTALARE DINTR-UN SINGUR FISIER
#
#  Copiaza acest fisier pe server si ruleaza O SINGURA DATA:
#
#      sudo bash agent-bundle.sh
#
#  Dupa asta, pentru totdeauna, scrii doar:
#
#      agent
#
#  Instaleaza dependentele, compileaza llama.cpp daca lipseste, descarca
#  modelul de embeddings, porneste serverele, indexeaza si te lasa in prompt.
